class DmaxDmaParserDocument(BaseModel):
    """Task document for parsing DMA outputs: moduli, phase, harmonics, and plots."""

    # --- analysis meta ---
    analysis_mode: str = Field(
        ..., description="Analysis method used: 'fft' (default) or 'fit'"
    )

    # --- primary mechanical properties ---
    storage_modulus: float = Field(..., description="Storage modulus G' in MPa")
    loss_modulus: float = Field(..., description="Loss modulus G'' in MPa")
    tan_delta: Optional[float] = Field(None, description="Loss tangent tan δ = G''/G'")
    elastic_modulus: float = Field(..., description="Elastic (Young) modulus from slope in MPa")
    poisson_ratio: float = Field(..., description="Poisson's ratio from lateral strain")

    # --- phase information ---
    phase_angle_rad: float = Field(..., description="Phase angle (radians)")
    phase_angle_deg: float = Field(..., description="Phase angle (degrees)")

    # --- harmonic / quality metrics (FFT mode) ---
    thd_pct: Optional[float] = Field(None, description="Total harmonic distortion (%) of pressure signal")
    snr_db: Optional[float] = Field(None, description="Signal‑to‑noise ratio of first harmonic (dB)")
    harmonic_magnitudes: Optional[Dict[int, float]] = Field(
        None,
        description="Relative magnitude |P_n|/|P_1| for n>1 (only present in FFT mode)",
    )

    # --- legacy fit diagnostics (fit mode) ---
    fit_r2: Optional[float] = Field(None, description="R² of sinusoidal fit (fit mode only)")
    fit_rmse: Optional[float] = Field(None, description="RMSE of sinusoidal fit in MPa (fit mode only)")
    amplitude: Optional[float] = Field(None, description="First‑harmonic pressure amplitude in MPa")

    # --- plot artefacts ---
    pressure_plot: str = Field(..., description="Path to pressure vs time plot with overlay")
    stress_strain_plot: str = Field(..., description="Path to stress–strain (Lissajous) plot")
    poisson_plot: Optional[str] = Field(None, description="Path to Poisson ratio vs strain/time plot")
    spectrum_plot: Optional[str] = Field(None, description="Path to magnitude‑spectrum (FFT) plot")


